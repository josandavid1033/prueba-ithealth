CREATE PROCEDURE AllPatient
AS BEGIN 
	BEGIN TRY	
			SET NOCOUNT ON

			SELECT P.NAME, DT.DOCUMENT_TYPE DOCUMENT_TYPE, P.DOCUMENT_NUM,
					Birthday, Email, G.NAME GENDER, Address, Phone_number, State
			FROM DBO.PATIENTS P 
			JOIN DBO.GENDERS G ON G.ID = P.GENDER_ID
			JOIN DBO.DOCUMENTS_TYPE DT ON DT.ID = P.DOCUMENT_TYPE_ID

	END TRY
	BEGIN CATCH
	END CATCH
END
			